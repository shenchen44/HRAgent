"""简历去标识 —— 抹掉敏感属性后再交给下游。

为什么需要它：`RecruitMatch` 与逐技能精排都要把简历整段交给 LLM。
简历首行是 `曹磊　|　男　|　31岁　|　未婚　|　9年经验` —— 性别/年龄/婚育
明写在里面，模型读得到。exp6 量过这件事的代价：同一套余弦，只换输入文本，
DI 从 0.356（读敏感字段）变成 0.935（去掉敏感字段、去掉姓名）。

所以本模块的定位是**风控件**而不是文本工具：它降低的是"打分器读到了不该读的东西"
这一类风险。exp6 用它做对照臂，前端用它做精排的输入。

**它不是匿名化**：正文里的项目经历仍可能透露年龄、婚育（"2015 年本科毕业"）。
去掉首行只是把最直接的通道堵上，这一点不能含糊 —— exp6 的 DI 也从未达到 1.0。
"""

from __future__ import annotations

import re

# 简历首行形如：曹磊　|　男　|　31岁　|　未婚　|　9年经验
# 敏感属性（性别/年龄/婚育）就明写在里面。**它们是随机分配的、与相关性无关**，
# 所以任何打分器只要读到了这一行，就会在 DI 上表现出来。
# 拆成两档是为了定位**通道**：去掉敏感字段后还偏，那就是姓名在带信息。
_RESUME_HEAD = re.compile(r"^([^\n|]+?)[\s　]*\|[\s　]*"
                          r"[^\n|]+?[\s　]*\|[\s　]*"
                          r"\d+岁[\s　]*\|[\s　]*"
                          r"[^\n|]+?[\s　]*\|[\s　]*"
                          r"(.+?)[\s　]*$", re.M)


def deident(text: str, drop_name: bool) -> str:
    """抹掉首行的敏感属性。drop_name=True 时连姓名也换成占位符。

    首行不符合该格式时**原样返回**（不报错）。它是尽力而为的过滤器：
    对格式外的简历它什么也做不了，调用方不该以为已经安全。
    """
    def sub(m: re.Match) -> str:
        who = "候选人" if drop_name else m.group(1)
        return f"{who}　|　{m.group(2)}"
    return _RESUME_HEAD.sub(sub, text, count=1)
